#!/usr/bin/env bash
# BE-7 — the fork's pages/_assets/quantum_chess.html is a hand-synced copy of
# this file (the "golden rule" in HANDOFF.md: edit canonical here first,
# test, then copy). This script IS that copy step — and it writes the exact
# sha256 the fork's CI vendor-check compares against (scripts/check_vendor.sh
# in the fork repo), so "the copy" and "the thing CI verifies" can never
# drift apart from each other the way the golden rule alone already has
# (embed-height, gate-rule text — see HANDOFF.md's BE-5/BE-7 notes).
#
# Usage: scripts/sync_vendor.sh <path-to-qublitz-fork-checkout>
set -euo pipefail

SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/quantum_chess.html"
FORK_DIR="${1:?Usage: scripts/sync_vendor.sh <path-to-qublitz-fork-checkout>}"
DEST_DIR="$FORK_DIR/pages/_assets"

if [ ! -f "$SRC" ]; then
  echo "error: $SRC not found" >&2
  exit 1
fi
if [ ! -d "$DEST_DIR" ]; then
  echo "error: $DEST_DIR not found — is $FORK_DIR the qublitz fork checkout?" >&2
  exit 1
fi

cp "$SRC" "$DEST_DIR/quantum_chess.html"
SHA="$(shasum -a 256 "$SRC" | awk '{print $1}')"
echo "$SHA" > "$DEST_DIR/VENDOR_SHA"

# VENDOR_SHA stays a bare hash and nothing else: the fork's scripts/check_vendor.sh reads it
# with `tr -d '[:space:]'`, so a second line in that file would silently corrupt the comparison
# and turn the drift guard into a permanent failure. Provenance therefore goes in its own file.
#
# Added 2026-08-23. Lane 3's acceptance criterion is that the vendor record "names the exact
# source commit", and a file hash alone does not — it proves the copy matches, but not what it
# was copied FROM, which is the question anyone auditing the deployed game actually has.
SRC_DIR="$(cd "$(dirname "$SRC")" && pwd)"
GIT_COMMIT="$(git -C "$SRC_DIR" rev-parse HEAD 2>/dev/null || echo "unknown")"
GIT_DESCRIBE="$(git -C "$SRC_DIR" describe --tags --always 2>/dev/null || echo "unknown")"
GIT_DIRTY=""
if ! git -C "$SRC_DIR" diff --quiet -- "$SRC" 2>/dev/null; then
  GIT_DIRTY="  ** WARNING: quantum_chess.html had uncommitted changes when this was vendored. **"
fi

cat > "$DEST_DIR/VENDOR_SOURCE.md" <<EOF
# Vendored game — provenance

Generated by the game repo's \`scripts/sync_vendor.sh\`. Do not edit by hand; re-run the script.

| Field | Value |
|---|---|
| Source commit | \`$GIT_COMMIT\` |
| Source describe | \`$GIT_DESCRIBE\` |
| File sha256 | \`$SHA\` |
| Vendored (UTC) | $(date -u +"%Y-%m-%d %H:%M:%SZ") |
$GIT_DIRTY

\`VENDOR_SHA\` holds the sha256 alone, because \`scripts/check_vendor.sh\` compares that file
byte-for-byte after stripping whitespace. This file is the human-readable half.
EOF

echo "Synced $SRC"
echo "   -> $DEST_DIR/quantum_chess.html"
echo "sha256: $SHA"
echo "source: $GIT_COMMIT ($GIT_DESCRIBE)"
[ -n "$GIT_DIRTY" ] && echo "$GIT_DIRTY"
echo "Wrote $DEST_DIR/VENDOR_SHA and VENDOR_SOURCE.md — commit them together in the fork repo."
